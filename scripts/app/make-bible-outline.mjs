// Makes src/data/bibleOutline.ts, the Bible's outline that ships inside the app: every book in order with its
// name, code, testament and how many verses each chapter has. No Bible words. It reads the database with the
// app's public key from .env.local. Run it again only if the database's books or chapters change:
//   node scripts/app/make-bible-outline.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';

/** Where the outline file goes. */
const OUT = 'src/data/bibleOutline.ts';

/** The most rows the database sends in one reply. */
const PAGE_ROWS = 1000;

/** Reads the KEY=value lines of .env.local. */
function readEnv() {
  const lines = readFileSync('.env.local', 'utf8').split(/\r?\n/).filter((l) => l.includes('='));
  return Object.fromEntries(lines.map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]));
}

const env = readEnv();
const db = createClient(env.EXPO_PUBLIC_SUPABASE_URL, env.EXPO_PUBLIC_SUPABASE_KEY, { auth: { persistSession: false } });

const books = await db.from('book').select('id, order, name, abbreviation, testament').order('order');
if (books.error) throw books.error;
if (books.data.length !== 66) throw new Error(`Expected 66 books, got ${books.data.length}.`);

const chapters = [];
for (let from = 0; ; from += PAGE_ROWS) {
  const page = await db.from('chapter').select('book_id, chapter_number, verse_count').range(from, from + PAGE_ROWS - 1);
  if (page.error) throw page.error;
  chapters.push(...page.data);
  if (page.data.length < PAGE_ROWS) break;
}

const rows = books.data.map((b) => {
  const own = chapters.filter((c) => c.book_id === b.id).sort((x, y) => x.chapter_number - y.chapter_number);
  own.forEach((c, i) => {
    if (c.chapter_number !== i + 1) throw new Error(`${b.name} is missing chapter ${i + 1}.`);
  });
  const book = { order: b.order, name: b.name, code: b.abbreviation, testament: b.testament, chapterVerses: own.map((c) => c.verse_count) };
  return `  ${JSON.stringify(book)},`;
});

const file = `// GENERATED by scripts/app/make-bible-outline.mjs from the database. Do not edit by hand.
// The Bible's outline, shipped inside the app so the book list opens with no download: every book in order
// with its name, code, testament and how many verses each chapter has. No Bible words.
// To make it again: node scripts/app/make-bible-outline.mjs

import type { BibleOutline } from '@/types/bible';

/** Every book of the Bible, in order. */
export const BIBLE_OUTLINE: BibleOutline = [
${rows.join('\n')}
];
`;
writeFileSync(OUT, file);
console.log(`Wrote ${OUT}: ${rows.length} books, ${chapters.length} chapters.`);
